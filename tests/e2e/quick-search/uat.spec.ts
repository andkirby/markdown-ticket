const shortcut = `${process.platform === 'darwin' ? 'Meta' : 'Control'}+k`

test('MDT-136 numbers and text stay local until All projects is enabled', async ({ page, e2eContext }) => {
  const current = await createExternalReferenceProject(e2eContext)
  const other = await createExternalReferenceProject(e2eContext)
  const local = await current.ticket('Uat Location Needle Login', ['work:PRJ-20'])
  const remote = await other.ticket('Uat Location Needle Redirect', ['work:PRJ-20'])
  await other.ticket('Uat Location Unrelated', [])
  await page.goto(`/prj/${current.project.key}`)
  await waitForBoardReady(page)
  await page.keyboard.press(shortcut)
  const input = page.locator(qs.input)
  const toggle = page.locator(qs.allProjects)
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await input.fill('20')
  await expect(page.locator(qs.results)).toContainText(local.code)
  await expect(page.locator(qs.results)).not.toContainText(remote.code)
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator(qs.results)).toContainText(remote.code)
  await expect(input).toHaveValue('20')
  await input.fill('needle uat location')
  await expect(page.locator(qs.results)).toContainText(local.code)
  await expect(page.locator(qs.results)).toContainText(remote.code)
  await expect(page.locator(qs.results)).not.toContainText('Uat Location Unrelated')
  await input.fill('')
  await expect(page.locator(qs.resultItem)).toHaveCount(0)
  await expect(page.locator(qs.noResults)).toBeVisible()
  await input.fill('needle uat location')
  await expect(page.locator(qs.results)).toContainText(remote.code)
  await toggle.click()
  await expect(page.locator(qs.results)).not.toContainText(remote.code)
  await expect(input).toHaveValue('needle uat location')
  await page.keyboard.press('Escape')
  await page.keyboard.press(shortcut)
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
})

