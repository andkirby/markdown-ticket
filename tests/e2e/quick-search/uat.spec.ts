test('MDT-136 focus stays inside Quick Search and returns to its opener', async ({ page, e2eContext }) => {
  const fixture = await createExternalReferenceProject(e2eContext)
  await fixture.ticket('Uat Focus Boundary', ['work:PRJ-95'])
  await page.goto(`/prj/${fixture.project.key}`)
  await waitForBoardReady(page)
  const opener = page.locator('nav button').first()
  await opener.focus()
  await page.keyboard.press(shortcut)
  const input = page.locator(qs.input)
  const help = page.locator(qs.keyboardHelp)
  await expect(input).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(help).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(input).toBeFocused()
  await expect(page.getByRole('dialog', { name: 'Quick search' })).toHaveAttribute('aria-modal', 'true')
  await page.keyboard.press('Escape')
  await expect(opener).toBeFocused()
})
