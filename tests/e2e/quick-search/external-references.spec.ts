import { expect, test } from '../fixtures/test-fixtures.js'
import { createExternalReferenceProject } from '../setup/external-references.js'
import { boardSelectors, externalReferenceSelectors, quickSearchSelectors, ticketSelectors } from '../utils/selectors.js'

test('MDT-252 key-shaped search combines local and external identities without duplication', async ({ request, e2eContext }) => {
  const first = await createExternalReferenceProject(e2eContext)
  const query = `${first.project.key}-1`
  const local = await first.ticket('Both local and external identity', [`work:${query}`])
  const second = await createExternalReferenceProject(e2eContext)
  const external = await second.ticket('External counterpart', [`work:${query}`])
  const response = await request.post(`${e2eContext.backendUrl}/api/projects/search`, { data: { mode: 'ticket_key', query } })
  expect(response.ok()).toBe(true)
  const body = await response.json()
  const matches = body.results.filter((item: { project: { code: string }, ticket: { code: string } }) =>
    (item.project.code === first.project.key && item.ticket.code === local.code)
    || (item.project.code === second.project.key && item.ticket.code === external.code),
  )
  expect(matches).toHaveLength(2)
  expect(matches.find((item: { project: { code: string } }) => item.project.code === first.project.key).matchedBy).toEqual(expect.arrayContaining(['local-key', 'external-ref']))
  expect(matches.find((item: { project: { code: string } }) => item.project.code === second.project.key).ticket.externalRefs).toHaveLength(1)
})

test('MDT-252 partial external matches require explicit result selection', async ({ page, e2eContext }) => {
  const fixture = await createExternalReferenceProject(e2eContext)
  const ticket = await fixture.ticket('Partial identity result', ['work:PRJ-11', 'gl:acme/platform/api#12', 'gh:acme/unique-widget-repository#88'])
  await page.goto(`/prj/${fixture.project.key}`)
  await expect(page.locator(boardSelectors.ticketByCode(ticket.code))).toBeVisible()
  await page.keyboard.press(`${process.platform === 'darwin' ? 'Meta' : 'Control'}+k`)
  await page.locator(quickSearchSelectors.input).fill('unique-widget')
  await expect(page.locator(quickSearchSelectors.results)).toContainText(ticket.code)
  await expect(page.locator(quickSearchSelectors.results).locator(externalReferenceSelectors.link).first()).toContainText('unique-widget-repository#88')
  await expect(page.locator(quickSearchSelectors.modal)).toBeVisible()
  await expect(page.locator(ticketSelectors.detailPanel)).not.toBeVisible()
})

test('MDT-252 numeric and git-only searches retain external badges when board badges are hidden', async ({ page, e2eContext }) => {
  const fixture = await createExternalReferenceProject(e2eContext)
  const jira = await fixture.ticket('Jira acceptance result', ['work:PRJ-123'])
  const git = await fixture.ticket('Repository acceptance result', ['gh:acme/widgets#123'])
  const different = await fixture.ticket('Different issue number', ['gh:acme/widgets#1234'])
  await page.addInitScript(() => {
    localStorage.setItem('markdown-ticket:board:ticket-card-badges:v2', JSON.stringify(['status', 'type']))
    localStorage.setItem('markdown-ticket:external-references-preference-migrated', 'true')
  })
  await page.goto(`/prj/${fixture.project.key}`)
  await expect(page.locator(boardSelectors.ticketByCode(git.code))).toBeVisible()
  await page.keyboard.press(`${process.platform === 'darwin' ? 'Meta' : 'Control'}+k`)
  const input = page.locator(quickSearchSelectors.input)
  await input.fill('123')
  await expect(page.locator(quickSearchSelectors.results)).toContainText(jira.code)
  await expect(page.locator(quickSearchSelectors.results)).toContainText(git.code)
  await input.fill('#123')
  await expect(page.locator(quickSearchSelectors.results)).toContainText(git.code)
  await expect(page.locator(quickSearchSelectors.results)).not.toContainText(jira.code)
  await expect(page.locator(quickSearchSelectors.results)).not.toContainText(different.code)
  await expect(page.locator(quickSearchSelectors.results).locator(externalReferenceSelectors.link)).toContainText('widgets#123')
  await input.fill('Repository acceptance')
  await expect(page.locator(quickSearchSelectors.results).locator(externalReferenceSelectors.link)).toContainText('widgets#123')
})

test('MDT-252 physical keyboard reaches result links and details, then returns to search', async ({ page, e2eContext }) => {
  const fixture = await createExternalReferenceProject(e2eContext)
  const ticket = await fixture.ticket('Independent search controls', ['gh:acme/widgets#123'])
  await fixture.ticket('Independent search second result', ['work:PRJ-7'])
  await page.goto(`/prj/${fixture.project.key}`)
  await expect(page.locator(boardSelectors.ticketByCode(ticket.code))).toBeVisible()
  await page.keyboard.press(`${process.platform === 'darwin' ? 'Meta' : 'Control'}+k`)
  const input = page.locator(quickSearchSelectors.input)
  await expect(input).toBeFocused()
  await input.fill('Independent search')
  const results = page.locator(quickSearchSelectors.results)
  await expect(results.locator('.search-result')).toHaveCount(2)
  await page.keyboard.press('ArrowDown')
  const selected = results.locator('.search-result[data-selected="true"]')
  await expect(selected).toContainText(ticket.code)
  await page.keyboard.press('F6')
  await expect(selected.locator('.search-result__select')).toBeFocused()
  await page.keyboard.press('Tab')
  const link = selected.locator(externalReferenceSelectors.link)
  await expect(link).toBeFocused()
  await page.context().route('https://github.example.test/**', route => route.fulfill({ body: '<h1>Issue</h1>', contentType: 'text/html' }))
  const popup = page.waitForEvent('popup')
  await page.keyboard.press('Enter')
  await (await popup).close()
  await expect(page.locator(quickSearchSelectors.modal)).toBeVisible()
  await expect(page.locator(ticketSelectors.detailPanel)).not.toBeVisible()
  await page.keyboard.press('Tab')
  const trigger = selected.locator(externalReferenceSelectors.detailsTrigger)
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator(externalReferenceSelectors.details)).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Shift+F6')
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('Independent search')
  await input.fill('no-such-result-mdt252')
  await expect(results).not.toBeVisible()
  await page.keyboard.press('F6')
  await expect(input).toBeFocused()
})

test('MDT-252 board query filters stored references with git-only number semantics', async ({ page, e2eContext }) => {
  const fixture = await createExternalReferenceProject(e2eContext)
  const jira = await fixture.ticket('Board Jira', ['work:PRJ-123'])
  const git = await fixture.ticket('Board git', ['unknown:org/widgets#123'])
  const longer = await fixture.ticket('Board longer git', ['gh:org/widgets#1234'])
  await page.goto(`/prj/${fixture.project.key}`)
  await expect(page.locator(boardSelectors.ticketByCode(jira.code))).toBeVisible()
  const search = page.locator('[data-testid="search-input"]')
  await search.fill('123')
  await expect(page.locator(boardSelectors.ticketByCode(jira.code))).toBeVisible()
  await expect(page.locator(boardSelectors.ticketByCode(git.code))).toBeVisible()
  await search.fill('#123')
  await expect(page.locator(boardSelectors.ticketByCode(git.code))).toBeVisible()
  await expect(page.locator(boardSelectors.ticketByCode(jira.code))).toHaveCount(0)
  await expect(page.locator(boardSelectors.ticketByCode(longer.code))).toHaveCount(0)
})

test('MDT-252 exact current-project key stays ahead of cross-project partial refs', async ({ page, request, e2eContext }) => {
  const first = await createExternalReferenceProject(e2eContext)
  const exact = await first.ticket('Exact local identity', [])
  const other = await createExternalReferenceProject(e2eContext)
  const partial = await other.ticket('Partial external identity', [`work:${exact.code}4`])
  await page.goto(`/prj/${first.project.key}`)
  await expect(page.locator(boardSelectors.ticketByCode(exact.code))).toBeVisible()
  await page.keyboard.press(`${process.platform === 'darwin' ? 'Meta' : 'Control'}+k`)
  await page.locator(quickSearchSelectors.input).fill(exact.code)
  const rows = page.locator('[data-testid="quick-search-cross-project-result-item"]')
  await expect(rows.first()).toContainText(exact.code)
  await expect(rows.nth(1)).toContainText(partial.code)
  const scoped = await request.post(`${e2eContext.backendUrl}/api/projects/search`, { data: { mode: 'project_scope', query: exact.code, projectCode: first.project.key, limitPerProject: 1 } })
  expect((await scoped.json()).results[0].ticket.code).toBe(exact.code)
})
